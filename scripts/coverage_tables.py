"""Generate the kinds, coverage and entry tables of docs/catalogues.md from the packaged data.

Run ``make docs-tables`` after changing a catalogue; ``tests/test_docs.py`` fails until the page
matches. Only the blocks between the generated-block markers are rewritten. The coverage tables
come from ``apb_catalog.api.rule_coverage``, the rule check ``apb-catalog check`` prints.
"""

from __future__ import annotations

import re
from collections.abc import Callable
from pathlib import Path
from typing import cast

import polars as pl

from apb_catalog.api import rule_coverage
from apb_catalog.source import (
    ProducerCatalogue,
    SourceCatalogues,
    SourceEntry,
    packaged_catalogues,
    packaged_descriptions,
)

PAGE = Path(__file__).resolve().parents[1] / "docs" / "catalogues.md"
BEGIN = "<!-- generated by scripts/coverage_tables.py: {name} -->"
END = "<!-- end of generated block: {name} -->"
ABSENT = "✗"

LEVELS = ("protein", "peptide", "peptidoform", "ion")
KIND_ORDER = ("pep", "q_value", "library_q_value", "global_q_value")
STAGE_ORDER = ("identification", "quantification")

NOTES: dict[tuple[str, str, str], str] = {("APB2", "ion", "charge"): "in `ProForma_ion`"}
"""Producer cells that hold a field inside another column rather than as a column of its own."""

CELLS = (
    "A cell names the APB column that answers, with the vendor columns APB2 computes it from"
    f" (`apb_Decoy` ← `Decoy`); {ABSENT} means nothing is catalogued."
)
LEGENDS: dict[str, str] = {
    "identification_confidence": (
        f"Coverage by software version, one table per level. {CELLS} Per run is a layer, one"
        " value per sample; per feature is a var column, one value across the experiment."
    ),
    "proteobench_entrapment": (
        f"Coverage by software version, for the vendors that carry entries. {CELLS} Per run is"
        " a layer, one value per sample."
    ),
    "miape": (
        " the draft specifies for it plus the shared `raw` layer; the ion table is APB's proposed"
        f" modality. {CELLS} Vendor rows show only what the vendor's export supplies. The APB2"
        " row shows APB2's canonical columns, answered where the level has them. The apb-fasta"
        " row answers after `apb-fasta verify-peptides`; until then its fields answer `unknown`."
    ),
}
EVERY_VENDOR_ROW = {
    "identification_confidence": True,
    "proteobench_entrapment": False,
    "miape": True,
}


def _version_key(label: str) -> tuple[int, ...]:
    match = re.match(r"(\d+)(?:\.(\d+))?", label)
    return tuple(int(number) for number in match.groups() if number) if match else ()


def _field(entry: SourceEntry) -> str:
    reference = entry.reference
    if reference.table is not None:
        return f"`{reference.table}.{reference.name}`"
    return f"`{reference.name}`"


def _row_field(row: Row) -> str:
    """The answering column of one coverage row, with the vendor columns APB2 computes it from."""
    name = f"`{row['table']}.{row['column']}`" if row["table"] else f"`{row['column']}`"
    inputs = cast(list[str], row["inputs"] or [])
    if row["producer"] is not None or row["location"] != "var" or not inputs:
        return name
    return f"{name} ← " + ", ".join(f"`{column}`" for column in inputs)


def _row(cells: list[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def _table(lead_in: str, header: list[str], rows: list[list[str]]) -> str:
    lines = [
        lead_in,
        "",
        '<div class="coverage-matrix" markdown>',
        "",
        _row(["Software", "Version", *header]),
        _row(["---", "---", *[":-:"] * (len(header))]),
        *(_row(row) for row in rows),
        "",
        "</div>",
    ]
    return "\n".join(lines)


type Row = dict[str, object]
type Column = tuple[str, ...]


def _miape_column(row: Row) -> Column:
    return (cast(str, row["kind"]),)


def _confidence_column(row: Row) -> Column:
    feature = "run" if row["location"] == "layers" else "feature"
    qualifiers = dict(
        pair.split("=", 1) for pair in cast(str, row["qualifiers"] or "").split(";") if pair
    )
    return (cast(str, row["kind"]), feature, qualifiers["stage"])


def _confidence_header(column: Column) -> str:
    kind, feature, stage = column
    return f"`{kind}` per {feature}" + (", MS1 peak" if stage == "quantification" else "")


def _supported(rows: list[Row]) -> list[Row]:
    return [row for row in rows if row["column"] is not None]


def _cells(columns: list[Column], rows: list[Row], column_of: Callable[[Row], Column]) -> list[str]:
    by_column: dict[Column, list[str]] = {}
    for row in _supported(rows):
        cells = by_column.setdefault(column_of(row), [])
        if _row_field(row) not in cells:
            cells.append(_row_field(row))
    return ["; ".join(by_column[column]) if column in by_column else ABSENT for column in columns]


def _columns(name: str, rows: list[Row]) -> tuple[list[Column], list[str]]:
    """The coverage columns of one level: required fields in order, or the fields found."""
    if name == "miape":
        required = dict.fromkeys(
            (cast(str, row["kind"]), cast(str, row["requirement"]))
            for row in rows
            if row["requirement"] is not None
        )
        columns: list[Column] = [(kind,) for kind, _ in required]
        return columns, [f"`{kind}` {requirement}" for kind, requirement in required]
    vendor = [row for row in _supported(rows) if row["producer"] is None]
    found = {_confidence_column(row) for row in vendor}
    columns = sorted(
        found,
        key=lambda column: (
            column[1] != "run",
            KIND_ORDER.index(column[0]),
            STAGE_ORDER.index(column[2]),
        ),
    )
    return columns, [_confidence_header(column) for column in columns]


def _coverage(name: str) -> list[str]:
    """One coverage table per level that the set's entries or modalities cover."""
    miape = name == "miape"
    column_of: Callable[[Row], Column] = _miape_column if miape else _confidence_column
    coverage = rule_coverage(name)
    with_entries = set(
        coverage.filter(pl.col("producer").is_null() & pl.col("column").is_not_null())
        .get_column("software")
        .to_list()
    )
    blocks: list[str] = []
    for level in LEVELS:
        rows = coverage.filter(pl.col("level") == level).to_dicts()
        columns, header = _columns(name, rows)
        variants: dict[tuple[str, str, str], list[Row]] = {}
        for row in rows:
            if EVERY_VENDOR_ROW[name] or row["software"] in with_entries:
                key = (
                    cast(str, row["software"]),
                    cast(str, row["version"]),
                    cast(str, row["rule"]),
                )
                variants.setdefault(key, []).append(row)
        producers: dict[str, list[Row]] = {}
        for row in rows:
            if row["producer"] is not None:
                producers.setdefault(cast(str, row["producer"]), []).append(row)
        if not columns or not (variants or producers):
            continue
        ordered = sorted(variants, key=lambda key: (key[0].lower(), _version_key(key[1])))
        table_rows = [
            [
                software,
                version,
                *_cells(
                    columns,
                    [row for row in variants[(software, version, rule)] if row["producer"] is None],
                    column_of,
                ),
            ]
            for software, version, rule in ordered
        ]
        for producer, entries in producers.items():
            cells = [
                NOTES.get((producer, level, column[0]), cell) if cell == ABSENT else cell
                for column, cell in zip(columns, _cells(columns, entries, column_of), strict=True)
            ]
            table_rows.append([producer, _scope(cast(str | None, entries[0]["needs"])), *cells])
        lead_in = f"{level.capitalize()} level{', proposed' if miape and level == 'ion' else ''}:"
        blocks.append(_table(lead_in, header, table_rows))
    return blocks


def _scope(needs: str | None) -> str:
    return "every rule" if needs is None else "after " + needs.removeprefix("run ")


def _producer_scope(producer: ProducerCatalogue) -> str:
    return _scope(producer.instruction)


def _requirement_levels(sources: SourceCatalogues, kind: str) -> str:
    """Where a kind is required and how strongly, such as ``MUST on protein and ion``."""
    by_requirement: dict[str, list[str]] = {}
    for level, required in sources.requirements.items():
        if kind in required:
            by_requirement.setdefault(required[kind], []).append(level)
    return "; ".join(
        f"{requirement} on "
        + ", ".join(levels[:-1])
        + (" and " if levels[:-1] else "")
        + levels[-1]
        for requirement, levels in by_requirement.items()
    )


def _kinds(sources: SourceCatalogues) -> list[str]:
    entries = [
        entry for source in (*sources.catalogues, *sources.producers) for entry in source.entries
    ]
    concepts = sorted({entry.concept for entry in entries})
    required = {kind for kinds in sources.requirements.values() for kind in kinds}
    lines: list[str] = []
    for concept_name in concepts:
        concept = sources.vocabulary.concept(concept_name)
        used = {entry.qualifiers["kind"] for entry in entries if entry.concept == concept_name}
        used |= required
        heading = "kinds and where they are required" if required else "kinds"
        lines += [f"Concept `{concept_name}`, {heading}:", ""]
        lines += [
            f"- `{kind}`, {_requirement_levels(sources, kind)}: {text}"
            if kind in required
            else f"- `{kind}`: {text}"
            for kind, text in concept.qualifiers["kind"].values.items()
            if kind in used
        ]
        if "origin" in concept.qualifiers:
            lines += ["", "Origins, the `origin` qualifier every entry declares:", ""]
            lines += [
                f"- `{value}`: {text}"
                for value, text in concept.qualifiers["origin"].values.items()
            ]
    return lines


def _entries(sources: SourceCatalogues) -> list[str]:
    lines = [
        "Every entry:",
        "",
        _row(["Software", "Rules", "Level", "Location", "APB field", "Kind"]),
        _row(["---"] * 6),
    ]
    for catalogue in sorted(sources.catalogues, key=lambda c: c.software_name.lower()):
        if not catalogue.entries:
            lines.append(_row([catalogue.software_name, "all", "—", "—", "none relevant", "—"]))
        for entry in catalogue.entries:
            rules = ", ".join(rule.removesuffix("/rules.json") for rule in entry.rules)
            lines.append(_entry_row(catalogue.software_name, rules, entry))
    for producer in sources.producers:
        for entry in producer.entries:
            lines.append(_entry_row(producer.producer, _producer_scope(producer), entry))
    return lines


def _entry_row(software: str, rules: str, entry: SourceEntry) -> str:
    reference = entry.reference
    return _row(
        [
            software,
            rules,
            reference.level,
            reference.location,
            _field(entry),
            f"`{entry.qualifiers['kind']}`",
        ]
    )


def block(name: str) -> str:
    """The generated part of one catalogue set's section."""
    sources = packaged_catalogues(name)
    parts = [
        "\n".join(_kinds(sources)),
        LEGENDS[name],
        *_coverage(name),
        "\n".join(_entries(sources)),
    ]
    return "\n\n".join(parts)


def render(page: str) -> str:
    """Return the page with every set's generated block rebuilt from the packaged data."""
    for name in packaged_descriptions():
        begin, end = BEGIN.format(name=name), END.format(name=name)
        if page.count(begin) != 1 or page.count(end) != 1:
            raise ValueError(f"the page needs exactly one generated block for {name!r}")
        head, rest = page.split(begin)
        _, tail = rest.split(end)
        page = f"{head}{begin}\n\n{block(name)}\n\n{end}{tail}"
    return page


def main() -> None:
    """Rewrite docs/catalogues.md in place."""
    PAGE.write_text(render(PAGE.read_text("utf-8")), "utf-8")


if __name__ == "__main__":
    main()
