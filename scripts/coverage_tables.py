"""Generate the kinds, coverage and entry tables of docs/catalogues.md from the packaged data.

Run ``make docs-tables`` after changing a catalogue; ``tests/test_docs.py`` fails until the page
matches. Only the blocks between the generated-block markers are rewritten. The coverage tables
come from ``apb_catalog.api.rule_coverage``, the rule check ``apb-catalog check`` prints.
"""

from __future__ import annotations

import re
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import cast

import polars as pl

from apb_catalog.api import rule_coverage
from apb_catalog.source import (
    ProducerCatalogue,
    SourceCatalogues,
    SourceEntry,
    packaged_catalogues,
    packaged_descriptions,
)

PAGE = Path(__file__).resolve().parents[1] / "docs" / "catalogues.md"
BEGIN = "<!-- generated by scripts/coverage_tables.py: {name} -->"
END = "<!-- end of generated block: {name} -->"
ABSENT = "✗"

LEVELS = ("protein", "peptide", "peptidoform", "peptidoform_ion", "peptidoform_fragment")
KIND_ORDER = ("pep", "q_value", "library_q_value", "global_q_value")
STAGE_ORDER = ("identification", "quantification")
ABUNDANCE_ORDER = ("intensity", "ms1_intensity", "maxlfq", "ibaq", "directlfq", "unknown")
NORMALIZATION_ORDER = ("none", "run_setting", "unknown")
QUALIFIER_LEADS = {
    "origin": "Origins, the `origin` qualifier every entry declares:",
    "normalization": "Normalization, the `normalization` qualifier every entry declares:",
    "unit": "Original time units, the `unit` qualifier every entry declares:",
}

CELLS = (
    "A cell names the APB column that answers, with the vendor columns APB2 computes it from"
    f" (`apb_Decoy` ← `Decoy`); {ABSENT} means nothing is catalogued."
)
LEGENDS: dict[str, str] = {
    "chromatography": (
        f"Coverage by software version, one table per level. {CELLS} Units describe the original"
        " values; `unknown` units must be resolved before converting to seconds. Per-run RT"
        " layers and a feature's experiment-wide RT annotation are different locations."
    ),
    "abundance": (
        f"Coverage by software version, one table per level. {CELLS} A column pairs a kind with"
        " its normalization; `unknown` marks what the evidence does not establish."
    ),
    "confidence": (
        f"Coverage by software version, one table per level. {CELLS} Per run is a layer, one"
        " value per sample; per feature is a var column, one value across the experiment."
    ),
    "apb": (
        "APB writes these fields itself, so they need no vendor review: the fixed columns keep"
        " their names for every vendor, a role names the var column the level's rule marks, and"
        " a prefix finds a sample-annotation column of the convention the result records."
        " `apb-catalog check apb` checks every packaged rule level against the requirements."
    ),
    "proteobench_entrapment": (
        f"Coverage by software version, for the vendors that carry entries. {CELLS} Per run is"
        " a layer, one value per sample; per feature is a var column, one value across the"
        " experiment."
    ),
}
EVERY_VENDOR_ROW = {
    "chromatography": True,
    "abundance": True,
    "confidence": True,
    "proteobench_entrapment": False,
    "apb": False,
}


def _version_key(label: str) -> tuple[int, ...]:
    match = re.match(r"(\d+)(?:\.(\d+))?", label)
    return tuple(int(number) for number in match.groups() if number) if match else ()


def _field(entry: SourceEntry) -> str:
    reference = entry.reference
    if reference.role is not None:
        return f"role `{reference.role}`"
    if reference.prefix is not None:
        return f"column starting `{reference.prefix}`"
    if reference.table is not None:
        return f"`{reference.table}.{reference.name}`"
    return f"`{reference.name}`"


def _row_field(row: Row) -> str:
    """The answering column of one coverage row, with the vendor columns APB2 computes it from."""
    name = f"`{row['table']}.{row['column']}`" if row["table"] else f"`{row['column']}`"
    inputs = cast(list[str], row["inputs"] or [])
    if row["producer"] is not None or row["location"] != "var" or not inputs:
        return name
    return f"{name} ← " + ", ".join(f"`{column}`" for column in inputs)


def _row(cells: list[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def _table(lead_in: str, header: list[str], rows: list[list[str]]) -> str:
    lines = [
        lead_in,
        "",
        '<div class="coverage-matrix" markdown>',
        "",
        _row(["Software", "Version", *header]),
        _row(["---", "---", *[":-:"] * (len(header))]),
        *(_row(row) for row in rows),
        "",
        "</div>",
    ]
    return "\n".join(lines)


type Row = dict[str, object]
type Column = tuple[str, ...]


def _qualifiers(row: Row) -> dict[str, str]:
    return dict(
        pair.split("=", 1) for pair in cast(str, row["qualifiers"] or "").split(";") if pair
    )


def _confidence_column(row: Row) -> Column:
    feature = "run" if row["location"] == "layers" else "feature"
    return (cast(str, row["kind"]), feature, _qualifiers(row)["stage"])


def _confidence_header(column: Column) -> str:
    kind, feature, stage = column
    return f"`{kind}` per {feature}" + (", MS1 peak" if stage == "quantification" else "")


def _confidence_order(column: Column) -> tuple[int, ...]:
    kind, feature, stage = column
    return (feature != "run", KIND_ORDER.index(kind), STAGE_ORDER.index(stage))


def _abundance_column(row: Row) -> Column:
    return (cast(str, row["kind"]), _qualifiers(row)["normalization"])


def _abundance_header(column: Column) -> str:
    kind, normalization = column
    return f"`{kind}`, `{normalization}`"


def _abundance_order(column: Column) -> tuple[int, ...]:
    kind, normalization = column
    return (ABUNDANCE_ORDER.index(kind), NORMALIZATION_ORDER.index(normalization))


def _kind_column(row: Row) -> Column:
    return (cast(str, row["kind"]),)


def _kind_header(column: Column) -> str:
    return f"`{column[0]}`"


def _kind_order(column: Column) -> tuple[int, ...]:
    return (0,)


@dataclass(frozen=True)
class Style:
    """How one set's coverage rows become table columns, and what its entry rows show."""

    column: Callable[[Row], Column]
    header: Callable[[Column], str]
    order: Callable[[Column], tuple[int, ...]]
    shown: tuple[str, ...]


CONFIDENCE = Style(_confidence_column, _confidence_header, _confidence_order, ("kind",))
STYLES = {
    "abundance": Style(
        _abundance_column, _abundance_header, _abundance_order, ("kind", "normalization")
    ),
    "confidence": CONFIDENCE,
    "proteobench_entrapment": CONFIDENCE,
    "apb": Style(_kind_column, _kind_header, _kind_order, ("kind",)),
    "chromatography": Style(_kind_column, _kind_header, _kind_order, ("kind", "unit")),
}


def _supported(rows: list[Row]) -> list[Row]:
    return [row for row in rows if row["column"] is not None]


def _cells(style: Style, columns: list[Column], rows: list[Row]) -> list[str]:
    by_column: dict[Column, list[str]] = {}
    for row in _supported(rows):
        cells = by_column.setdefault(style.column(row), [])
        if _row_field(row) not in cells:
            cells.append(_row_field(row))
    return ["; ".join(by_column[column]) if column in by_column else ABSENT for column in columns]


def _columns(style: Style, rows: list[Row]) -> tuple[list[Column], list[str]]:
    """The coverage columns of one level: the fields the vendors supply."""
    vendor = [row for row in _supported(rows) if row["producer"] is None]
    columns = sorted({style.column(row) for row in vendor}, key=style.order)
    return columns, [style.header(column) for column in columns]


def _coverage(name: str, style: Style) -> list[str]:
    """One coverage table per level that the set's entries cover."""
    coverage = rule_coverage(name)
    with_entries = set(
        coverage.filter(pl.col("producer").is_null() & pl.col("column").is_not_null())
        .get_column("software")
        .to_list()
    )
    blocks: list[str] = []
    for level in LEVELS:
        rows = coverage.filter(pl.col("level") == level).to_dicts()
        columns, header = _columns(style, rows)
        variants: dict[tuple[str, str, str], list[Row]] = {}
        for row in rows:
            if EVERY_VENDOR_ROW[name] or row["software"] in with_entries:
                key = (
                    cast(str, row["software"]),
                    cast(str, row["version"]),
                    cast(str, row["rule"]),
                )
                variants.setdefault(key, []).append(row)
        producers: dict[str, list[Row]] = {}
        for row in rows:
            if row["producer"] is not None:
                producers.setdefault(cast(str, row["producer"]), []).append(row)
        if not columns or not (variants or producers):
            continue
        ordered = sorted(variants, key=lambda key: (key[0].lower(), _version_key(key[1])))
        table_rows = [
            [
                software,
                version,
                *_cells(
                    style,
                    columns,
                    [row for row in variants[(software, version, rule)] if row["producer"] is None],
                ),
            ]
            for software, version, rule in ordered
        ]
        for producer, entries in producers.items():
            needs = _scope(cast(str | None, entries[0]["needs"]))
            table_rows.append([producer, needs, *_cells(style, columns, entries)])
        blocks.append(_table(f"{level.capitalize()} level:", header, table_rows))
    return blocks


def _scope(needs: str | None) -> str:
    return "every rule" if needs is None else "after " + needs.removeprefix("run ")


def _producer_scope(producer: ProducerCatalogue) -> str:
    return _scope(producer.instruction)


def _requirement_levels(sources: SourceCatalogues, kind: str) -> str:
    """Where a kind is required and how strongly, such as ``MUST on protein and ion``."""
    by_requirement: dict[str, list[str]] = {}
    for row in sources.requirements:
        if row.kind == kind:
            qualified = "".join(f" with {name} `{value}`" for name, value in row.qualifiers.items())
            by_requirement.setdefault(row.requirement + qualified, []).append(row.level)
    return "; ".join(
        f"{requirement} on "
        + ", ".join(levels[:-1])
        + (" and " if levels[:-1] else "")
        + levels[-1]
        for requirement, levels in by_requirement.items()
    )


def _kinds(sources: SourceCatalogues) -> list[str]:
    entries = [entry for source in sources.sources() for entry in source.entries]
    vocabulary = sources.vocabulary
    required = {row.kind for row in sources.requirements}
    used = {entry.qualifiers["kind"] for entry in entries} | required
    heading = "Kinds and where they are required" if required else "Kinds"
    lines = [f"{heading}:", ""]
    lines += [
        f"- `{kind}`, {_requirement_levels(sources, kind)}: {text}"
        if kind in required
        else f"- `{kind}`: {text}"
        for kind, text in vocabulary.qualifiers["kind"].values.items()
        if kind in used
    ]
    for qualifier, lead in QUALIFIER_LEADS.items():
        if qualifier in vocabulary.qualifiers:
            lines += ["", lead, ""]
            lines += [
                f"- `{value}`: {text}"
                for value, text in vocabulary.qualifiers[qualifier].values.items()
            ]
    return lines


def _entries(sources: SourceCatalogues, style: Style) -> list[str]:
    shown = [qualifier.capitalize() for qualifier in style.shown]
    lines = [
        "Every entry:",
        "",
        _row(["Software", "Rules", "Level", "Location", "APB field", *shown]),
        _row(["---"] * (5 + len(shown))),
    ]
    for catalogue in sorted(sources.catalogues, key=lambda c: c.software_name.lower()):
        if not catalogue.entries:
            lines.append(
                _row(
                    [catalogue.software_name, "all", "—", "—", "none relevant", *["—"] * len(shown)]
                )
            )
        for entry in catalogue.entries:
            rules = ", ".join(rule.removesuffix("/rules.json") for rule in entry.rules)
            lines.append(_entry_row(style, catalogue.software_name, rules, entry))
    for producer in sources.producers:
        for entry in producer.entries:
            lines.append(_entry_row(style, producer.producer, _producer_scope(producer), entry))
    for annotation in sources.annotations:
        scope = f"{annotation.convention} annotation"
        for entry in annotation.entries:
            lines.append(_entry_row(style, "APB2 annotate", scope, entry))
    return lines


def _entry_row(style: Style, software: str, rules: str, entry: SourceEntry) -> str:
    reference = entry.reference
    return _row(
        [
            software,
            rules,
            reference.level,
            reference.location,
            _field(entry),
            *(f"`{entry.qualifiers[qualifier]}`" for qualifier in style.shown),
        ]
    )


def block(name: str) -> str:
    """The generated part of one catalogue set's section."""
    sources = packaged_catalogues(name)
    style = STYLES[name]
    parts = [
        "\n".join(_kinds(sources)),
        LEGENDS[name],
        *_coverage(name, style),
        "\n".join(_entries(sources, style)),
    ]
    return "\n\n".join(parts)


def render(page: str) -> str:
    """Return the page with every set's generated block rebuilt from the packaged data."""
    for name in packaged_descriptions():
        begin, end = BEGIN.format(name=name), END.format(name=name)
        if page.count(begin) != 1 or page.count(end) != 1:
            raise ValueError(f"the page needs exactly one generated block for {name!r}")
        head, rest = page.split(begin)
        _, tail = rest.split(end)
        page = f"{head}{begin}\n\n{block(name)}\n\n{end}{tail}"
    return page


def main() -> None:
    """Rewrite docs/catalogues.md in place."""
    PAGE.write_text(render(PAGE.read_text("utf-8")), "utf-8")


if __name__ == "__main__":
    main()
