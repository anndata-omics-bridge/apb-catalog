"""Generate the tables of docs/catalogues.md from the packaged catalogue data.

Run ``make docs-tables`` after changing a catalogue; ``tests/test_docs.py`` fails until the page
matches. Only the blocks between the generated-block markers are rewritten: one listing every
set, and one per set with its vocabulary, requirements, coverage and fields. The coverage
tables come from ``apb_catalog.api.rule_coverage``, the rule check ``apb-catalog check`` prints.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import cast

import polars as pl

from apb_catalog.api import catalogues, rule_coverage
from apb_catalog.coverage import version_label
from apb_catalog.source import (
    SourceCatalogues,
    SourceEntry,
    packaged_catalogues,
    packaged_descriptions,
)

PAGE = Path(__file__).resolve().parents[1] / "docs" / "catalogues.md"
BEGIN = "<!-- generated by scripts/coverage_tables.py: {name} -->"
END = "<!-- end of generated block: {name} -->"
SETS = "sets"
PRESENT = "✓"
ABSENT = "·"
UNKNOWN = "unknown"

LEVELS = ("protein", "peptide", "peptidoform", "peptidoform_ion", "peptidoform_fragment")
LOCATIONS = ("layers", "var", "varm", "obs")
VALUE_QUALIFIERS = ("unit",)
"""Qualifiers that describe a field's values rather than choose its meaning: shown beside the
field, not as coverage columns of their own."""

type Row = dict[str, object]
type Column = tuple[str, ...]


def _row(cells: list[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def _table(header: list[str], rows: list[list[str]], *, centred_from: int | None = None) -> str:
    aligns = [
        ":-:" if centred_from is not None and index >= centred_from else "---"
        for index in range(len(header))
    ]
    return "\n".join([_row(header), _row(aligns), *(_row(row) for row in rows)])


def _code(text: str) -> str:
    return f"`{text}`"


def _version_key(label: str) -> tuple[int, ...]:
    match = re.match(r"(\d+)(?:\.(\d+))?", label)
    return tuple(int(number) for number in match.groups() if number) if match else ()


class Vocabulary:
    """The order and wording a set's vocabulary gives its qualifiers and values."""

    def __init__(self, sources: SourceCatalogues) -> None:
        self._qualifiers = sources.vocabulary.qualifiers

    def meaning_qualifiers(self) -> tuple[str, ...]:
        """The qualifiers besides ``kind`` that choose a meaning, in vocabulary order."""
        return tuple(
            name for name in self._qualifiers if name != "kind" and name not in VALUE_QUALIFIERS
        )

    def value_qualifiers(self) -> tuple[str, ...]:
        """The qualifiers that describe a field's values, in vocabulary order."""
        return tuple(name for name in self._qualifiers if name in VALUE_QUALIFIERS)

    def rank(self, qualifier: str, value: str) -> int:
        """A value's position in its qualifier's vocabulary; ``unknown`` comes last."""
        values = list(self._qualifiers[qualifier].values)
        return values.index(value) if value in values else len(values)

    def table(self, used: dict[str, set[str]]) -> str:
        """Every qualifier value the set's fields use, with its meaning."""
        rows: list[list[str]] = []
        for name, qualifier in self._qualifiers.items():
            meanings = {**qualifier.values, UNKNOWN: "The evidence does not establish it."}
            rows += [
                [_code(name), _code(value), text]
                for value, text in meanings.items()
                if value in used.get(name, set())
            ]
        return _table(["Qualifier", "Value", "Meaning"], rows)


def _used_values(sources: SourceCatalogues) -> dict[str, set[str]]:
    used: dict[str, set[str]] = {}
    for source in sources.sources():
        for entry in source.entries:
            for name, value in entry.qualifiers.items():
                used.setdefault(name, set()).add(value)
    for row in sources.requirements:
        used.setdefault("kind", set()).add(row.kind)
        for name, value in row.qualifiers.items():
            used.setdefault(name, set()).add(value)
    return used


# ------------------------------------------------------------------------------- requirements


def _requirements(sources: SourceCatalogues, vocabulary: Vocabulary) -> str | None:
    """How strongly the set needs each kind on each level; ``None`` for a set without rows."""
    if not sources.requirements:
        return None
    levels = [level for level in LEVELS if any(row.level == level for row in sources.requirements)]
    by_meaning: dict[tuple[str, str, str], dict[str, str]] = {}
    for row in sources.requirements:
        qualifiers = ", ".join(f"{name}={value}" for name, value in row.qualifiers.items())
        by_meaning.setdefault((row.kind, row.location, qualifiers), {})[row.level] = row.requirement
    ordered = sorted(
        by_meaning,
        key=lambda key: (vocabulary.rank("kind", key[0]), LOCATIONS.index(key[1]), key[2]),
    )
    qualified = any(key[2] for key in ordered)
    header = ["Kind", "Location", *(["Qualifiers"] if qualified else []), *levels]
    rows = [
        [
            _code(kind),
            location,
            *([_code(qualifiers) if qualifiers else ""] if qualified else []),
            *(by_meaning[(kind, location, qualifiers)].get(level, ABSENT) for level in levels),
        ]
        for kind, location, qualifiers in ordered
    ]
    return _table(header, rows, centred_from=len(header) - len(levels))


# ----------------------------------------------------------------------------------- coverage


def _qualifiers(row: Row) -> dict[str, str]:
    pairs = cast(str, row["qualifiers"] or "").split(";")
    found = dict(pair.split("=", 1) for pair in pairs if pair)
    if row["origin"] is not None:
        found["origin"] = cast(str, row["origin"])
    return found


def _column(row: Row, vocabulary: Vocabulary) -> Column:
    qualifiers = _qualifiers(row)
    return (
        cast(str, row["location"]),
        cast(str, row["kind"]),
        *(qualifiers[name] for name in vocabulary.meaning_qualifiers()),
    )


def _column_order(column: Column, vocabulary: Vocabulary) -> tuple[int, ...]:
    location, kind, *values = column
    return (
        LOCATIONS.index(location),
        vocabulary.rank("kind", kind),
        *(
            vocabulary.rank(name, value)
            for name, value in zip(vocabulary.meaning_qualifiers(), values, strict=True)
        ),
    )


def _column_header(column: Column, *, located: bool) -> str:
    """The kind, the values of its other meaning qualifiers, and the location where it varies."""
    location, kind, *values = column
    return ", ".join([_code(kind), *values]) + (f" ({location})" if located else "")


def _coverage(name: str, vocabulary: Vocabulary) -> list[str]:
    """One matrix per level: a row per software version, a column per meaning and location."""
    coverage = rule_coverage(name)
    vendor = coverage.filter(pl.col("producer").is_null())
    blocks: list[str] = []
    for level in LEVELS:
        rows = vendor.filter(pl.col("level") == level).to_dicts()
        supplied = [row for row in rows if row["column"] is not None]
        columns = sorted(
            {_column(row, vocabulary) for row in supplied},
            key=lambda column: _column_order(column, vocabulary),
        )
        if not columns:
            continue
        variants: dict[tuple[str, str], list[Row]] = {}
        for row in rows:
            key = (cast(str, row["software"]), cast(str, row["version"]))
            variants.setdefault(key, []).append(row)
        ordered = sorted(variants, key=lambda key: (key[0].lower(), _version_key(key[1])))
        located = len({column[0] for column in columns}) > 1
        judged = any(row["verdict"] is not None for row in rows)
        header = [
            "Software",
            "Version",
            *(_column_header(column, located=located) for column in columns),
        ]
        if judged:
            header.append("Check")
        table_rows: list[list[str]] = []
        for software, version in ordered:
            found = {
                _column(row, vocabulary)
                for row in variants[(software, version)]
                if row["column"] is not None
            }
            cells = [PRESENT if column in found else ABSENT for column in columns]
            if judged:
                cells.append(cast(str | None, variants[(software, version)][0]["verdict"]) or "")
            table_rows.append([software, version, *cells])
        blocks.append(
            "\n".join(
                [
                    f"**{level}**" + ("" if located else f", all `{columns[0][0]}`"),
                    "",
                    '<div class="coverage-matrix" markdown>',
                    "",
                    _table(header, table_rows, centred_from=2),
                    "",
                    "</div>",
                ]
            )
        )
    return blocks


# ------------------------------------------------------------------------------------- fields


def _field(entry: SourceEntry) -> str:
    reference = entry.reference
    if reference.role is not None:
        return f"role {_code(reference.role)}"
    if reference.prefix is not None:
        return f"{_code(reference.prefix)}…"
    if reference.table is not None:
        return _code(f"{reference.table}.{reference.name}")
    return _code(cast(str, reference.name))


def _scope(instruction: str | None) -> str:
    return "every rule" if instruction is None else "after " + instruction.removeprefix("run ")


def _sourced(sources: SourceCatalogues) -> list[tuple[str, str, SourceEntry]]:
    """Every entry with who supplies it and for which versions."""
    found: list[tuple[str, str, SourceEntry]] = []
    for catalogue in sources.catalogues:
        labels = {
            variant.rule: version_label(variant.software_version_pattern)
            for variant in catalogue.variants
        }
        for entry in catalogue.entries:
            versions = sorted({labels[rule] for rule in entry.rules}, key=_version_key)
            found.append((catalogue.software_name, ", ".join(versions), entry))
    for producer in sources.producers:
        found += [(producer.producer, _scope(producer.instruction), e) for e in producer.entries]
    for annotation in sources.annotations:
        scope = f"{annotation.convention} annotation"
        found += [("APB2 annotate", scope, entry) for entry in annotation.entries]
    return found


@dataclass(frozen=True)
class FieldRow:
    """One catalogued field as the Fields tables show it, before its levels are merged."""

    kind: str
    location: str
    meaning: tuple[str, ...]
    software: str
    versions: str
    field: str
    values: tuple[str, ...]

    def order(self, vocabulary: Vocabulary) -> tuple[object, ...]:
        """Location first, then the meaning qualifiers, then software, versions and field."""
        return (
            LOCATIONS.index(self.location),
            *(
                vocabulary.rank(name, value)
                for name, value in zip(vocabulary.meaning_qualifiers(), self.meaning, strict=True)
            ),
            self.software.lower(),
            _version_key(self.versions),
            self.field,
        )


def _first_of_group(group: list[str], previous: list[str]) -> list[str]:
    """The grouping cells of one row, each shown only where it or a cell before it changed."""
    changed = next(
        (
            index
            for index, (now, then) in enumerate(zip(group, previous, strict=False))
            if now != then
        ),
        min(len(group), len(previous)),
    )
    return ["" if index < changed else cell for index, cell in enumerate(group)]


PER_KIND = 2
"""A set averaging this many fields per kind gets one table per kind; fewer share one table."""


def _fields(sources: SourceCatalogues, vocabulary: Vocabulary) -> list[str]:
    """The catalogued fields, sorted by kind; a field catalogued on several levels is one row."""
    meaning = vocabulary.meaning_qualifiers()
    values = vocabulary.value_qualifiers()
    levels: dict[FieldRow, set[str]] = {}
    for software, versions, entry in _sourced(sources):
        row = FieldRow(
            kind=entry.qualifiers["kind"],
            location=entry.reference.location,
            meaning=tuple(entry.qualifiers[name] for name in meaning),
            software=software,
            versions=versions,
            field=_field(entry),
            values=tuple(entry.qualifiers[name] for name in values),
        )
        levels.setdefault(row, set()).add(entry.reference.level)
    header = [
        "Location",
        *(name.capitalize() for name in meaning),
        "Software",
        "Versions",
        "APB field",
        *(name.capitalize() for name in values),
        "Levels",
    ]
    kinds = sorted({row.kind for row in levels}, key=lambda kind: vocabulary.rank("kind", kind))
    split = len(levels) >= PER_KIND * len(kinds)
    blocks: list[str] = []
    rows: list[list[str]] = []
    for kind in kinds:
        previous: list[str] = []
        for row in sorted(
            (row for row in levels if row.kind == kind), key=lambda row: row.order(vocabulary)
        ):
            group = [
                *([] if split else [_code(kind)]),
                row.location,
                *(_code(value) for value in row.meaning),
            ]
            rows.append(
                [
                    *_first_of_group(group, previous),
                    row.software,
                    row.versions,
                    row.field,
                    *(_code(value) for value in row.values),
                    ", ".join(sorted(levels[row], key=LEVELS.index)),
                ]
            )
            previous = group
        if split:
            blocks.append(f"**{_code(kind)}**\n\n" + _table(header, rows))
            rows = []
    return blocks if split else [_table(["Kind", *header], rows)]


# --------------------------------------------------------------------------------- the page


def sets_block() -> str:
    """Every packaged set: what it holds, who uses it, and how many entries it has."""
    rows = [
        [
            f"[{_code(row['catalogue'])}](#{row['catalogue']})",
            row["purpose"],
            "<br>".join(row["used_by"]),
            str(row["entries"]),
        ]
        for row in catalogues()
        .filter(pl.col("catalogue").is_in(list(packaged_descriptions())))
        .sort("catalogue")
        .to_dicts()
    ]
    return _table(["Set", "Holds", "Used by", "Entries"], rows)


def block(name: str) -> str:
    """The generated part of one catalogue set's section."""
    sources = packaged_catalogues(name)
    vocabulary = Vocabulary(sources)
    parts = ["### Vocabulary", vocabulary.table(_used_values(sources))]
    requirements = _requirements(sources, vocabulary)
    if requirements is not None:
        parts += ["### Requirements", requirements]
    coverage = _coverage(name, vocabulary)
    if coverage:
        parts += ["### Coverage", *coverage]
    parts += ["### Fields", *_fields(sources, vocabulary)]
    return "\n\n".join(parts)


def render(page: str) -> str:
    """Return the page with the set list and every set's block rebuilt from the packaged data."""
    for name in (SETS, *packaged_descriptions()):
        begin, end = BEGIN.format(name=name), END.format(name=name)
        if page.count(begin) != 1 or page.count(end) != 1:
            raise ValueError(f"the page needs exactly one generated block for {name!r}")
        head, rest = page.split(begin)
        _, tail = rest.split(end)
        body = sets_block() if name == SETS else block(name)
        page = f"{head}{begin}\n\n{body}\n\n{end}{tail}"
    return page


def main() -> None:
    """Rewrite docs/catalogues.md in place."""
    PAGE.write_text(render(PAGE.read_text("utf-8")), "utf-8")


if __name__ == "__main__":
    main()
